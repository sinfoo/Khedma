// Interview question bank. Bilingual, tagged by track, type and level (1 easy … 3 hard).
// `hints` = what a good answer covers; they also feed the offline scorer's relevance check.

export const TRACKS = ["stage", "pfe", "junior", "data", "embedded", "netsec"] as const;
export type Track = (typeof TRACKS)[number];
export const QTYPES = ["behavioral", "technical", "motivation", "situational", "culture"] as const;
export type QType = (typeof QTYPES)[number];
export type Level = 1 | 2 | 3;
export type Lang = "fr" | "en";

export interface BankQuestion {
  id: string;
  type: QType;
  level: Level;
  tracks: readonly Track[];
  en: string;
  fr: string;
  hints: { en: string[]; fr: string[] };
}

const ALL = TRACKS;
const DEV: Track[] = ["stage", "pfe", "junior"];
const split = (s: string) => s.split(" | ").map((x) => x.trim()).filter(Boolean);
const q = (id: string, type: QType, level: Level, tracks: readonly Track[], en: string, fr: string, hen: string, hfr: string): BankQuestion => ({
  id,
  type,
  level,
  tracks,
  en,
  fr,
  hints: { en: split(hen), fr: split(hfr) },
});

